"""Native adapters for pnpm/Yarn Berry lockfiles and resolved Maven/Gradle graphs.

YAML is parsed with PyYAML. These adapters never install packages or execute build scripts;
Maven TGF and Gradle JSON are generated by explicit, isolated CI collection steps.
"""
import json
import pathlib
import re


def _yaml(path):
    try:
        import yaml
    except ImportError as exc:
        raise ValueError("PyYAML is required for pnpm-lock.yaml and Yarn Berry yarn.lock; install requirements") from exc
    value = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"{path.name} must contain a YAML mapping")
    return value


def _row(ecosystem, name, version, source, dependencies=None, unresolved=None, **extra):
    unresolved = unresolved or []
    return {
        "ecosystem": ecosystem, "name": str(name), "version": str(version),
        "source": source, "dependencies": sorted(set(dependencies or [])),
        "unresolved_dependencies": unresolved, "graph_complete": not unresolved, **extra
    }


def _normal_name(value):
    return str(value).lower().replace("_", "-")


def _split_pnpm_key(key):
    value = str(key).lstrip("/")
    value = re.sub(r"\\([^()]*\\)$", "", value)
    match = re.match(r"^(@[^/]+/[^@]+|[^@]+)@([^()]+)$", value)
    if not match:
        return None
    return match.group(1), match.group(2)


def pnpm_lock(path):
    doc = _yaml(path)
    packages = doc.get("packages") or {}
    snapshots = doc.get("snapshots") or {}
    if not isinstance(packages, dict) or not isinstance(snapshots, dict):
        raise ValueError("pnpm packages/snapshots sections must be mappings")
    source_keys = snapshots if snapshots else packages
    records = []
    by_key = {}
    by_name = {}
    for key, snapshot in source_keys.items():
        identity = _split_pnpm_key(key)
        if not identity:
            continue
        name, version = identity
        metadata = packages.get(key, {}) if isinstance(packages.get(key), dict) else {}
        if not metadata and snapshots:
            metadata = next((v for k, v in packages.items() if _split_pnpm_key(k) == identity and isinstance(v, dict)), {})
        deps_map = {}
        if isinstance(metadata, dict):
            deps_map.update(metadata.get("dependencies") or {})
            deps_map.update(metadata.get("optionalDependencies") or {})
        if isinstance(snapshot, dict):
            deps_map.update(snapshot.get("dependencies") or {})
            deps_map.update(snapshot.get("optionalDependencies") or {})
        record = {"key": str(key), "name": name, "version": version, "deps": deps_map,
                  "source": str(path.name), "integrity": metadata.get("resolution", {}).get("integrity") if isinstance(metadata.get("resolution"), dict) else None}
        by_key[str(key)] = record
        by_name.setdefault(_normal_name(name), []).append(record)
        records.append(record)

    out = []
    for record in records:
        edges, unresolved = [], []
        for dep_name, selector in record["deps"].items():
            selector = str(selector).lstrip("/")
            exact_key = f"{dep_name}@{selector}"
            candidates = [by_key[k] for k in (exact_key, "/" + exact_key) if k in by_key]
            if not candidates:
                version = selector.split("(", 1)[0]
                candidates = [x for x in by_name.get(_normal_name(dep_name), []) if x["version"] == version]
            if len(candidates) == 1:
                hit = candidates[0]
                edges.append(f"{hit['name']}@{hit['version']}")
            else:
                unresolved.append(f"{dep_name} ({selector}; pnpm resolution ambiguous or missing)")
        out.append(_row("npm", record["name"], record["version"], record["source"], edges, unresolved,
                        lock_key=record["key"], integrity=record["integrity"]))
    return out


def _descriptor_name(descriptor):
    descriptor = str(descriptor).strip().strip('"').strip("'")
    if descriptor.startswith("@"):
        slash = descriptor.find("/")
        marker = descriptor.find("@", slash + 1)
    else:
        marker = descriptor.find("@")
    return descriptor[:marker] if marker > 0 else None


def _strip_protocol(spec):
    value = str(spec or "").strip()
    for prefix in ("npm:", "patch:", "virtual:"):
        if value.startswith(prefix):
            value = value[len(prefix):]
    if value.startswith("workspace:"):
        return value[len("workspace:"):]
    return value


def _version_matches(spec, version):
    spec = _strip_protocol(spec)
    if spec in ("", "*", "latest"):
        return True
    # Yarn aliases and URL/git/patch descriptors are not safely reducible to semver.
    if any(token in spec for token in ("git+", "https:", "file:", "portal:", "link:", "patch:")):
        return False
    spec = spec.replace("v", "", 1) if spec.startswith("v") else spec
    try:
        from dependency_graph import version_satisfies
        return version_satisfies(spec, version)
    except Exception:
        return False


def yarn_berry_lock(path):
    doc = _yaml(path)
    if "__metadata" not in doc:
        raise ValueError("yarn.lock is not recognized as Yarn Berry (Berry __metadata missing)")
    entries, by_name = [], {}
    for descriptor, data in doc.items():
        if descriptor == "__metadata" or not isinstance(data, dict) or not data.get("version"):
            continue
        resolution = str(data.get("resolution") or "")
        name = _descriptor_name(resolution) or _descriptor_name(descriptor)
        if not name:
            continue
        item = {"name": name, "version": str(data["version"]), "resolution": resolution or str(descriptor),
                "dependencies": data.get("dependencies") or {}, "optional": data.get("optionalDependencies") or {}}
        entries.append(item)
        by_name.setdefault(_normal_name(name), []).append(item)
    out = []
    for item in entries:
        edges, unresolved = [], []
        deps = dict(item["dependencies"])
        deps.update(item["optional"])
        for dep, spec in deps.items():
            candidates = [x for x in by_name.get(_normal_name(dep), []) if _version_matches(spec, x["version"])]
            if len(candidates) == 1:
                hit = candidates[0]
                edges.append(f"{hit['name']}@{hit['version']}")
            else:
                unresolved.append(f"{dep} ({spec}; Yarn Berry descriptor unresolved or ambiguous)")
        out.append(_row("npm", item["name"], item["version"], "yarn.lock (Berry)", edges, unresolved,
                        resolution=item["resolution"]))
    return out


def gradle_lock(path):
    """Exact Gradle lock coordinates; edges are attached from the resolved init-script JSON."""
    rows = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        value = line.split("#", 1)[0].strip()
        if not value or "=" not in value:
            continue
        coordinate, configurations = value.split("=", 1)
        parts = coordinate.strip().split(":")
        if len(parts) < 3:
            raise ValueError(f"invalid Gradle lock coordinate: {coordinate}")
        group, name, version = ":".join(parts[:-2]), parts[-2], parts[-1]
        rows.append({"group": group, "name": name, "version": version, "configurations": configurations.strip()})
    return rows


def gradle_resolved(path):
    doc = json.loads(path.read_text(encoding="utf-8"))
    if doc.get("schema_version") != "1.0" or not isinstance(doc.get("components"), list):
        raise ValueError("Gradle resolution graph has an unsupported schema")
    components = {}
    for item in doc["components"]:
        key = item.get("id")
        if not key or not item.get("group") or not item.get("name") or not item.get("version"):
            raise ValueError("Gradle graph contains a component without exact module coordinates")
        slot = components.setdefault(key, {"group": item["group"], "name": item["name"], "version": item["version"], "deps": set(), "configs": set()})
        slot["deps"].update(item.get("dependencies") or [])
        slot["configs"].update(item.get("configurations") or [])
    out = []
    for key, item in sorted(components.items()):
        edges, unresolved = [], []
        for dep in sorted(item["deps"]):
            if dep in components:
                hit = components[dep]
                edges.append(f"{hit['group']}:{hit['name']}@{hit['version']}")
            else:
                unresolved.append(f"{dep} (missing from resolved Gradle component set)")
        out.append(_row("Maven", item["name"], item["version"], "Gradle ResolutionResult",
                        edges, unresolved, group=item["group"], configurations=sorted(item["configs"]), component_id=key))
    if doc.get("failures"):
        for item in out:
            item["unresolved_dependencies"].extend(doc["failures"])
            item["graph_complete"] = False
    return out


def maven_tgf(path):
    """Parse Maven Dependency Plugin TGF output into exact package edges."""
    nodes, edges = {}, []
    reading_edges = False
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line:
            continue
        if line == "#":
            reading_edges = True
            continue
        if reading_edges:
            bits = line.split()
            if len(bits) >= 2:
                edges.append((bits[0], bits[1]))
        else:
            if line.startswith("#"):
                continue
            bits = line.split(None, 1)
            if len(bits) == 2:
                nodes[bits[0]] = bits[1].strip()
    parsed = {}
    for node_id, label in nodes.items():
        parts = label.split(":")
        if len(parts) < 5:
            continue
        group, artifact = parts[0], parts[1]
        if len(parts) == 5:
            version, scope = parts[3], parts[4]
            packaging = parts[2]
        else:
            version, scope = parts[-2], parts[-1]
            packaging = parts[2]
        parsed[node_id] = {"group": group, "name": artifact, "version": version, "scope": scope, "packaging": packaging}
    adjacency = {}
    for left, right in edges:
        adjacency.setdefault(left, set()).add(right)
    out = []
    for node_id, item in parsed.items():
        deps, unresolved = [], []
        for child in sorted(adjacency.get(node_id, set())):
            if child in parsed:
                hit = parsed[child]
                deps.append(f"{hit['group']}:{hit['name']}@{hit['version']}")
            else:
                unresolved.append(f"Maven TGF node {child} is missing or not a package")
        out.append(_row("Maven", item["name"], item["version"], str(path.name), deps, unresolved,
                        group=item["group"], scope=item["scope"], packaging=item["packaging"], node_id=node_id))
    if not out:
        raise ValueError(f"{path.name} contained no parseable Maven dependency nodes")
    return out
